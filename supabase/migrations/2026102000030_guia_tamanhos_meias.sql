<p><strong>Como escolher:</strong> comece pelo tornozelo (cB) e confirme com a barriga da perna (cC); para meias até à coxa e collants confirme também cF e cG. Se as medidas caírem em tamanhos diferentes, escolha pelo tornozelo e, na dúvida, fale connosco antes de comprar.</p>
<p>Nas meias de descanso em algodão, o tamanho vem também pelo número do pé: I (35–36), II (37–38), III (39–40), IV (41–42), V (43–44). Se as medidas da perna e o número do pé apontarem para tamanhos diferentes, siga as medidas da perna.</p>
<p>Lembre-se de que, por razões de higiene, as meias só podem ser devolvidas com a embalagem selada. Se tiver dúvidas sobre a compressão indicada para o seu caso, fale com o seu médico ou farmacêutico.</p>
