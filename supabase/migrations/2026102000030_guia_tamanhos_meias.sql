<h2>Calçado</h2>
<p>Meça o pé ao fim do dia, em pé, do calcanhar à ponta do dedo mais comprido. Se estiver entre dois números, escolha o maior.</p>
<p>Nas socas com numeração dupla (por exemplo 37/38), escolha pelo seu número habitual.</p>
<h2>Meias e collants de descanso e compressão (tamanhos I a V)</h2>
<p>O tamanho escolhe-se pelas medidas da perna, não pelo número do pé. Meça de manhã, ao levantar, antes de a perna inchar, com uma fita métrica justa mas sem apertar.</p>
<ol>
<li><strong>cB – tornozelo:</strong> a circunferência na zona mais fina, logo acima do osso do tornozelo. É a medida mais importante.</li>
<li><strong>cC – barriga da perna:</strong> a circunferência na zona mais larga.</li>
<li><strong>cD – abaixo do joelho:</strong> a circunferência logo abaixo do joelho (meias até ao joelho).</li>
<li><strong>cF – meio da coxa</strong> e <strong>cG – topo da coxa:</strong> só para meias até à coxa e collants.</li>
<li><strong>Alturas (aB a aG):</strong> do chão (calcanhar) até cada um desses pontos, com o pé assente.</li>
</ol>
